import json

with open('scratch/material_category_config.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

lines = []
lines.append("// Generated Material Form Configuration matching Web Portal materialCategoryConfig")
lines.append("class MaterialFormConfig {")
lines.append("  final String label;")
lines.append("  final List<String> options;")
lines.append("  final String specLabel;")
lines.append("  final List<String> specOptions;")
lines.append("  final List<String> units;")
lines.append("  final bool attachment;")
lines.append("")
lines.append("  const MaterialFormConfig({")
lines.append("    required this.label,")
lines.append("    required this.options,")
lines.append("    required this.specLabel,")
lines.append("    required this.specOptions,")
lines.append("    required this.units,")
lines.append("    this.attachment = false,")
lines.append("  });")
lines.append("}")
lines.append("")
lines.append("class MaterialFormRegistry {")
lines.append("  static const Map<String, MaterialFormConfig> configs = {")

for k, v in data.items():
    label_str = json.dumps(v.get('label', 'Item Type'))
    options_str = json.dumps(v.get('options', []))
    spec_label_str = json.dumps(v.get('specLabel', 'Specification'))
    spec_options_str = json.dumps(v.get('specOptions', []))
    units_str = json.dumps(v.get('units', ['Nos']))
    att_str = 'true' if v.get('attachment', False) else 'false'
    
    lines.append(f"    '{k}': MaterialFormConfig(")
    lines.append(f"      label: {label_str},")
    lines.append(f"      options: {options_str},")
    lines.append(f"      specLabel: {spec_label_str},")
    lines.append(f"      specOptions: {spec_options_str},")
    lines.append(f"      units: {units_str},")
    lines.append(f"      attachment: {att_str},")
    lines.append("    ),")

lines.append("  };")
lines.append("")
lines.append("  static MaterialFormConfig getConfig(String rawKey) {")
lines.append("    if (rawKey.isEmpty) {")
lines.append("      return const MaterialFormConfig(")
lines.append("        label: 'Item Type',")
lines.append("        options: [],")
lines.append("        specLabel: 'Size / Specification',")
lines.append("        specOptions: [],")
lines.append("        units: ['Nos', 'Units', 'Bags', 'Ton', 'Kg', 'Sq.Ft', 'Cft', 'Cum'],")
lines.append("      );")
lines.append("    }")
lines.append("")
lines.append("    final clean = rawKey.trim().toLowerCase().replaceAll(RegExp(r'[^a-z0-9]'), '');")
lines.append("    ")
lines.append("    if (configs.containsKey(clean)) {")
lines.append("      return configs[clean]!;")
lines.append("    }")
lines.append("")
lines.append("    if (clean.contains('brick') || clean.contains('block')) return configs['bricks']!;")
lines.append("    if (clean.contains('sand')) return configs['sand']!;")
lines.append("    if (clean.contains('cement')) return configs['cement']!;")
lines.append("    if (clean.contains('steel') || clean.contains('tmt')) return configs['steel']!;")
lines.append("    if (clean.contains('electric') || clean.contains('wire') || clean.contains('cable')) return configs['electricalwire']!;")
lines.append("    if (clean.contains('tile')) return configs['tiles']!;")
lines.append("    if (clean.contains('paint')) return configs['painting']!;")
lines.append("    if (clean.contains('plumb')) return configs['plumber']!;")
lines.append("    if (clean.contains('granite') || clean.contains('marble')) return configs['granite']!;")
lines.append("    if (clean.contains('jally')) return configs['jally']!;")
lines.append("    if (clean.contains('aggregate')) return configs['aggregate']!;")
lines.append("    if (clean.contains('gravel')) return configs['gravel']!;")
lines.append("    if (clean.contains('door') || clean.contains('window')) return configs['doorswindows']!;")
lines.append("    if (clean.contains('wood') || clean.contains('timber') || clean.contains('carpentr')) return configs['woodcarpentry']!;")
lines.append("    if (clean.contains('sanitary') || clean.contains('bath')) return configs['sanitarybathfittings']!;")
lines.append("    if (clean.contains('safety') || clean.contains('ppe')) return configs['safetyppe']!;")
lines.append("    if (clean.contains('hardware')) return configs['hardware']!;")
lines.append("    if (clean.contains('waterproof') || clean.contains('insulat')) return configs['waterproofinginsulation']!;")
lines.append("    if (clean.contains('roof')) return configs['roofing']!;")
lines.append("    if (clean.contains('glass') || clean.contains('alumin')) return configs['glassaluminium']!;")
lines.append("    if (clean.contains('weld')) return configs['welding']!;")
lines.append("    if (clean.contains('rmc')) return configs['rmc']!;")
lines.append("    if (clean.contains('rcconcrete') || clean.contains('concrete')) return configs['rcconcrete']!;")
lines.append("    if (clean.contains('lift')) return configs['lift']!;")
lines.append("    if (clean.contains('transport') || clean.contains('vehicle')) return configs['transport']!;")
lines.append("    if (clean.contains('interior')) return configs['interior']!;")
lines.append("    if (clean.contains('watercan')) return configs['watercan']!;")
lines.append("    if (clean.contains('lorry')) return configs['lorrywater']!;")
lines.append("    if (clean.contains('tea')) return configs['tea']!;")
lines.append("    if (clean.contains('scaffold') || clean.contains('formwork')) return configs['scaffoldingformwork']!;")
lines.append("    if (clean.contains('finish')) return configs['finishingmaterials']!;")
lines.append("    if (clean.contains('outdoor') || clean.contains('external')) return configs['externaloutdoor']!;")
lines.append("")
lines.append("    for (var entry in configs.entries) {")
lines.append("      if (clean.contains(entry.key) || entry.key.contains(clean)) {")
lines.append("        return entry.value;")
lines.append("      }")
lines.append("    }")
lines.append("")
lines.append("    return const MaterialFormConfig(")
lines.append("      label: 'Item Type',")
lines.append("      options: [],")
lines.append("      specLabel: 'Size / Specification',")
lines.append("      specOptions: [],")
lines.append("      units: ['Nos', 'Units', 'Bags', 'Ton', 'Kg', 'Sq.Ft', 'Cft', 'Cum'],")
lines.append("    );")
lines.append("  }")
lines.append("}")
lines.append("")

with open('lib/model/material_form_config.dart', 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

print("Successfully written lib/model/material_form_config.dart")
